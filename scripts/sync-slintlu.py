#!/usr/bin/env python3
"""Copies SlintLu's documentation into the site as Markdown pages.

Usage: scripts/sync-slintlu.py SLINTLU_CHECKOUT

README.md becomes /slintlu/ and docs/*.md become /slintlu/<name>/. Links between those files
are rewritten to the site; other relative links point at the SlintLu repository on GitHub.
The Pages workflow runs this against SlintLu's main branch before every build, and the copies
are committed so the site also builds on its own.
"""

import re
import sys
from pathlib import Path

REPOSITORY = "https://github.com/LunaDashWM/SlintLu/blob/main/"
# Source file → (page, sidebar title, summary). Testing notes stay in the repository.
PAGES = {
    "README.md": ("index", "SlintLu", "A toolkit for Wayland desktop shells written in the Slint language: bars, docks, launchers, overlays and lock screens, run without compiling."),
    "docs/API.md": ("api", "API reference", "Every component, global, struct and enum SlintLu offers to Slint shells, generated from the library sources."),
    "docs/IPC.md": ("ipc", "IPC and scripting", "Talk to a running shell from scripts and keyboard shortcuts with slintlu msg."),
    "docs/THEMING.md": ("theming", "Theming", "Palettes, the light and dark mode, and how shells follow the desktop's appearance."),
    "docs/I18N.md": ("i18n", "Translations", "Translate a shell with gettext catalogues and switch languages at runtime."),
    "docs/LOCKSCREEN.md": ("lockscreen", "Lock screen", "Build a secure lock screen with ext-session-lock and PAM authentication."),
}


def link_target(target: str) -> str:
    path, _, anchor = target.partition("#")
    anchor = f"#{anchor}" if anchor else ""
    if not path:
        return target
    normalized = path.removeprefix("../").removeprefix("./")
    if not normalized.startswith("docs/") and normalized != "README.md" and "/" not in path:
        # A sibling inside docs/.
        candidate = f"docs/{normalized}"
        if candidate in PAGES:
            normalized = candidate
    if normalized in PAGES:
        page = PAGES[normalized][0]
        # Relative to a page one level below /slintlu/ (the index is adjusted by the caller).
        return "../" + ("" if page == "index" else f"{page}/") + anchor
    return REPOSITORY + normalized + anchor


def convert(text: str, page: str, title: str, summary: str) -> str:
    # The layout prints the title; drop the document's own first heading and badges under it.
    lines = text.splitlines()
    while lines and (lines[0].startswith("# ") or not lines[0].strip()):
        lines.pop(0)
    body = "\n".join(lines)

    def replace(match: re.Match) -> str:
        label, target = match.group(1), match.group(2)
        if re.match(r"^[a-z]+:", target) or target.startswith("#"):
            return match.group(0)
        resolved = link_target(target)
        # Pages live one level below /slintlu/, except the index itself.
        if page == "index" and resolved.startswith("../"):
            resolved = resolved[3:] or "./"
        return f"[{label}]({resolved})"

    body = re.sub(r"\[([^\]]*)\]\(([^)\s]+)\)", replace, body)
    front = (
        "---\n"
        "layout: ../../layouts/MarkdownLayout.astro\n"
        f"title: {title!r}\n"
        f"summary: {summary!r}\n"
        f"section: slintlu-{page}\n"
        "---\n\n"
        "<!-- Generated by scripts/sync-slintlu.py from the SlintLu repository; edit it there. -->\n\n"
    )
    return front + body.strip() + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1])
    target = Path(__file__).resolve().parent.parent / "src" / "pages" / "slintlu"
    target.mkdir(parents=True, exist_ok=True)
    for name, (page, title, summary) in PAGES.items():
        text = (source / name).read_text(encoding="utf-8")
        (target / f"{page}.md").write_text(convert(text, page, title, summary), encoding="utf-8")
        print(f"{name} -> src/pages/slintlu/{page}.md")


if __name__ == "__main__":
    main()
